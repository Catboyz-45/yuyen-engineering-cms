/**
 * หน้าที่ของไฟล์นี้: เลือกรูปแบบป้ายเล็กเหนือหัวข้อ (eyebrow) ตามภาษาของข้อความ
 *
 * หมายเหตุสำหรับผู้อ่านที่ไม่เขียนโค้ด: ป้ายภาษาอังกฤษใช้ตัวพิมพ์ใหญ่และเว้นช่องไฟกว้าง แต่ถ้าเว้นช่องไฟแบบเดียวกันกับภาษาไทย
 * ตัวอักษรกับสระและวรรณยุกต์จะดูแยกห่างกัน อ่านยาก ป้ายที่มีอักษรไทยจึงใช้รูปแบบที่ไม่เว้นช่องไฟ
 */
const THAI = /[฀-๿]/;

export function eyebrowClass(text: string | null | undefined) {
  return text && THAI.test(text) ? "eyebrow eyebrow-th" : "eyebrow";
}
